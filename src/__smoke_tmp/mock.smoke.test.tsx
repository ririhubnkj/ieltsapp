import { render, screen, fireEvent, act } from '@testing-library/react';
import { MemoryRouter } from 'react-router-dom';
import { AppDataProvider } from '../context/AppDataContext';
import { ReadingMockScreen } from '../components/screens/ReadingMockScreen';

it('runs a mock end to end', () => {
  window.HTMLElement.prototype.scrollTo = () => {};
  window.HTMLElement.prototype.scrollIntoView = () => {};
  render(<MemoryRouter><AppDataProvider><ReadingMockScreen /></AppDataProvider></MemoryRouter>);
  expect(screen.getByText(/設問は全部で39問/)).toBeTruthy();
  fireEvent.click(screen.getByText('自分で選ぶ'));
  fireEvent.click(screen.getByText('60分の模試を始める'));
  expect(screen.getByRole('timer').textContent).toBe('60:00');
  fireEvent.click(screen.getAllByRole('tab')[1]!);
  fireEvent.click(screen.getByText('設問'));
  expect(screen.getAllByText(/Questions 14–/).length).toBeGreaterThan(0);
  expect(screen.getByText('14')).toBeTruthy();
  fireEvent.click(screen.getByText(/解答状況/));
  fireEvent.click(screen.getByLabelText('30(未回答)'));
  fireEvent.click(screen.getByText(/解答状況/));
  const btns = screen.getAllByText('提出して採点する');
  fireEvent.click(btns[btns.length - 1]!);
  expect(screen.getByText(/未回答が39問/)).toBeTruthy();
  act(() => { fireEvent.click(screen.getByText('提出する')); });
  expect(screen.getByText('模試の結果')).toBeTruthy();
  expect(screen.getByText('設問の形式ごとの正答率')).toBeTruthy();
  expect(JSON.parse(localStorage.getItem('ielts_reading_mock_v1')!)).toHaveLength(1);
  fireEvent.click(screen.getByText('Passage 1 から解説を見る'));
  fireEvent.click(screen.getAllByText(/本文の段落 .* を見る/)[0]!);
});
